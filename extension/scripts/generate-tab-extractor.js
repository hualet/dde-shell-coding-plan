#!/usr/bin/env node

const fs = require("fs");
const path = require("path");

const EXT_DIR = path.resolve(__dirname, "..");

function stripExports(code) {
  return code
    .replace(/^export\s+(const|let|var|function|class|async\s+function)\s/gm, "$1 ")
    .replace(/^export\s+\{[^}]*\}\s*;?\s*$/gm, "")
    .replace(/^export\s+default\s+/gm, "");
}

function findMatchingBrace(code, startIdx) {
  let depth = 0;
  let i = startIdx;
  while (i < code.length) {
    if (code[i] === "{") depth++;
    else if (code[i] === "}") {
      depth--;
      if (depth === 0) return i;
    }
    i++;
  }
  return -1;
}

function extractFunctionByName(code, name) {
  const regex = new RegExp(
    `(?:async\\s+)?function\\s+${name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*\\(`,
    "m"
  );
  const match = code.match(regex);
  if (!match) return null;
  const funcStart = match.index;
  const braceStart = code.indexOf("{", funcStart);
  if (braceStart < 0) return null;
  const braceEnd = findMatchingBrace(code, braceStart);
  if (braceEnd < 0) return null;
  return code.slice(funcStart, braceEnd + 1);
}

function extractMethodBody(code, objectVar, methodName) {
  const pattern = new RegExp(
    `${objectVar}\\s*=\\s*\\{[\\s\\S]*?${methodName}\\s*\\(`,
    "m"
  );
  return null;
}

function findExtractQuotaMethod(code, providerId) {
  const providerStart = code.indexOf(`id: "${providerId}"`);
  if (providerStart < 0) return null;

  const methodLabel = "extractQuota(";
  const methodIdx = code.indexOf(methodLabel, providerStart);
  if (methodIdx < 0) return null;

  const braceStart = code.indexOf("{", methodIdx);
  if (braceStart < 0) return null;
  const braceEnd = findMatchingBrace(code, braceStart);
  if (braceEnd < 0) return null;

  const fullMethod = code.slice(methodIdx, braceEnd + 1);
  const bodyOnly = code.slice(braceStart, braceEnd + 1);

  return {
    fullMethod,
    asFunction: `function(doc) ${bodyOnly}`
  };
}

const utilsCode = stripExports(
  fs.readFileSync(path.join(EXT_DIR, "shared/quota-utils.js"), "utf-8")
);

const providerSpecs = [
  { file: "providers/codex.js", id: "codex" },
  { file: "providers/kimi-code.js", id: "kimi-code" },
  { file: "providers/glm-coding.js", id: "glm-coding" },
  { file: "providers/minimax.js", id: "minimax" },
];

const PROVIDER_HELPERS = [
  "detailToQuota",
  "readBillingFromDoc",
  "readKimiDomFallback",
  "readGlmDomFallback",
  "cookieValue",
  "limitToQuota",
  "readQuotaFromDoc",
];

const allProviderCode = providerSpecs
  .map(s => fs.readFileSync(path.join(EXT_DIR, s.file), "utf-8"))
  .join("\n");
const strippedProviderCode = stripExports(allProviderCode);

const helperCode = PROVIDER_HELPERS
  .map(name => extractFunctionByName(strippedProviderCode, name))
  .filter(Boolean)
  .join("\n\n");

const providerEntries = providerSpecs.map(({ file, id }) => {
  const code = fs.readFileSync(path.join(EXT_DIR, file), "utf-8");
  const method = findExtractQuotaMethod(code, id);
  if (!method) {
    console.error(`Could not extract extractQuota from ${file}`);
    process.exit(1);
  }
  return `    "${id}": {\n      providerId: "${id}",\n      extract: ${method.asFunction}\n    }`;
}).join(",\n");

const output = `// Auto-generated by scripts/generate-tab-extractor.js — DO NOT EDIT
// Bundles shared quota utils + provider extractQuota functions into a single IIFE
// for use with chrome.scripting.executeScript (which cannot import ES modules).

(function() {
${utilsCode}

${helperCode}

  const PROVIDERS = {
${providerEntries}
  };

  window.__ddeExtractQuotaInPage = function(providerId) {
    const provider = PROVIDERS[providerId];
    if (!provider) return { success: false, error: "Unknown provider in tab" };

    const extraction = provider.extract(document);
    if (!extraction || !extraction.success) {
      const text = (document.body ? document.body.innerText : "").toLowerCase();
      const isLogin = text.includes("log in") || text.includes("sign in") || text.includes("\\u767b\\u5f55") || text.includes("login");
      if (isLogin) {
        return { success: false, error: "auth_error:\\u672a\\u767b\\u5f55 " + provider.providerId + "\\uff0c\\u8bf7\\u5148\\u5728\\u6d4f\\u89c8\\u5668\\u4e2d\\u767b\\u5f55" };
      }
      return { success: false, needsRetry: true, error: extraction?.reason || ("Could not find " + provider.providerId + " quota info on rendered page"), debug: extraction?.debug };
    }

    const parsed = extraction.raw;
    if (!parsed || (parsed.fiveHour == null && parsed.weekly == null)) {
      return { success: false, needsRetry: true, error: "Extracted raw data has no quota fields" };
    }

    const clamp = (v) => (Number.isFinite(v) ? Math.max(0, Math.min(1, v)) : -1);
    const pct = (v) => (v >= 0 ? Math.round(v * 100) + "%" : "");

    return {
      success: true,
      data: {
        providerId: provider.providerId,
        source: "browser_ext",
        status: "ok",
        weeklyRemainingRatio: parsed.weekly != null ? (parsed.weekly.ratio != null ? clamp(parsed.weekly.ratio) : clamp(parsed.weekly)) : -1,
        weeklyBalanceText: parsed.weekly != null ? (parsed.weekly.text != null ? parsed.weekly.text : pct(clamp(parsed.weekly))) : "",
        fiveHourRemainingRatio: parsed.fiveHour != null ? (parsed.fiveHour.ratio != null ? clamp(parsed.fiveHour.ratio) : clamp(parsed.fiveHour)) : -1,
        fiveHourBalanceText: parsed.fiveHour != null ? (parsed.fiveHour.text != null ? parsed.fiveHour.text : pct(clamp(parsed.fiveHour))) : "",
        remainingRatio: parsed.weekly != null ? (parsed.weekly.ratio != null ? clamp(parsed.weekly.ratio) : clamp(parsed.weekly)) : (parsed.fiveHour != null ? (parsed.fiveHour.ratio != null ? clamp(parsed.fiveHour.ratio) : clamp(parsed.fiveHour)) : -1),
        balanceText: parsed.weekly != null ? (parsed.weekly.text != null ? parsed.weekly.text : pct(clamp(parsed.weekly))) : (parsed.fiveHour != null ? (parsed.fiveHour.text != null ? parsed.fiveHour.text : pct(clamp(parsed.fiveHour))) : ""),
        updatedAt: new Date().toISOString(),
        _debug: parsed.debug || undefined,
      }
    };
  };
})();
`;

const outPath = path.join(EXT_DIR, "shared", "tab-extractor-iife.js");
fs.writeFileSync(outPath, output, "utf-8");
console.log("Built:", outPath, "(" + output.split("\n").length + " lines)");
